#!/usr/bin/env python3
"""levels/world*/NN_name.txt -> src/level_data.c  (1 byte/tile, const data; never copied into RAM buffers)"""
import glob
CH = {'.':0,'#':1,'=':2,'^':3,'H':4,'$':5,'C':6,'E':7,'x':8,'R':9,'G':10,'T':11,'z':13,'S':0,'k':0,'m':0}
files = sorted(glob.glob('levels/world*/*.txt'))
out = ['/* GENERATED by tools/mklevels.py - do not edit */', '#include "level.h"']
defs = []
for i, f in enumerate(files):
    L = open(f).read().splitlines(); meta = {}
    while ':' in L[0]: k, v = L.pop(0).split(':', 1); meta[k.strip()] = v.strip()
    rows = L; h = len(rows); w = len(rows[0]); spawn = None; ents = []
    assert all(len(r) == w for r in rows), f"{f}: ragged rows"
    assert w <= 96 and h == 15, f"{f}: bad size {w}x{h}"
    data = []
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == 'S': spawn = (x, y)
            if c == 'k': ents.append((0, x, y))
            if c == 'm': ents.append((1, x, y))
            data.append(CH[c])
    assert spawn, f"{f}: no spawn"
    out.append(f'static const uint8_t L{i}[{len(data)}] = {{' + ','.join(map(str, data)) + '};')
    ev = ents or [(255, 0, 0)]
    out.append(f'static const EntDef E{i}[{len(ev)}] = {{' + ','.join('{%d,%d,%d}' % e for e in ev) + '};')
    defs.append(f'  {{{meta["world"]},{w},{h},{spawn[0]},{spawn[1]},{meta.get("boss", 0)},{len(ents)},L{i},E{i},"{meta["name"]}"}}')
out.append('const LevelDef LEVELS[LEVELS_IMPLEMENTED] = {\n' + ',\n'.join(defs) + '\n};')
n = int([l for l in open('include/abyss.h') if 'define LEVELS_IMPLEMENTED' in l][0].split()[-1])
assert len(files) == n, f"{len(files)} level files but LEVELS_IMPLEMENTED={n}"
open('src/level_data.c', 'w').write('\n'.join(out) + '\n')
print(f'{len(files)} levels written')
